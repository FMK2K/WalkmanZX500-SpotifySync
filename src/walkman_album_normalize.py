"""
walkman_album_normalize.py — fix a *single* album folder that has duplicate
tracks and/or tracks in the wrong order.

walkman_deluxe_merge.py already does this, but only for folders that have a
genuine "<Album>" + "<Album> (Deluxe)" pair. A plain standalone album that
ended up with two full rips merged into one folder — e.g. Kanye West's
Late Registration with a 21-track FLAC rip (every title suffixed
"(Album Version (Explicit))"), a 21-track plain-titled MP3 rip, and a few
"(feat. X)" M4As, all in Music/Kanye West/Late Registration/ = 47 files for
21 songs — is never touched by any existing pass:
  - Pass 3 dedup only compares SAME-extension files with matching track keys
  - deluxe_merge skips it (no suffixed sibling folder)

This tool walks every album folder. For the ones with a duplicate signal it
fetches the canonical Deezer tracklist and matches EACH file to a canonical
track by fuzzy title (parens / "- remaster" / "(Album Version)" / feat.
stripped) with the file's own track number as the tie-breaker. Then:
  1. files that matched the SAME canonical track are duplicates -> keep the
     best (protected > FLAC > MP3 > M4A, then larger), HARD-delete the rest
     (user direction 2026-09-07: hard delete, not soft)
  2. every surviving matched file is renamed to
     "<Artist> - <Album> - NN <Canonical Title>.<ext>"  (NN = canonical #)
  3. files that match no canonical track are left completely alone

Anchoring on the canonical tracklist (not raw title strings) is what lets
"Diamonds From Sierra Leone - Remix" (canon #13) and "Diamonds From Sierra
Leone" (canon #20) stay as two separate tracks while four differently-tagged
copies of "We Major" collapse to one.

Favorited / playlisted files are protected from DELETION — a favorited copy
always wins its keep-slot over a better-quality non-favorite, so the star is
never orphaned. They ARE renamed to the canonical number: a favorite is
content-matched by the Sony DB so it re-attaches on the next "Update
database" rescan, and the playlist M3U8s are regenerated by the favsync
stage that runs after this one. (Run this standalone -> re-run favsync
after.)

Usage:
    python walkman_album_normalize.py                 # dry-run report
    python walkman_album_normalize.py --execute
    python walkman_album_normalize.py --execute --artist "Kanye West"
"""
from __future__ import annotations

import argparse
import difflib
import json
import os
import sys
import collections
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import config
import adb_transfer as adb
import walkman_dedup as wd
import album_completeness as ac
import walkman_deluxe_merge as dm      # _base_album / _split_name / _QUAL / _sanitize / _NUM
import device_library as _dl           # _fuzzy_norm_title

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

MUSIC_ROOT = getattr(config, "MUSIC_ROOT", "Music")
TRASH = getattr(config, "DEDUP_SOFT_DELETE_FOLDER", ".deleted")
_TMP = ".__norm_tmp"
_MATCH_MIN = 0.86      # fuzzy title score to accept a canonical-track match
_fz = _dl._fuzzy_norm_title
ROOT = Path(__file__).resolve().parent.parent / "state"   # <repo>/state (src/ reorg)
TAGFIX_STATE = ROOT / "album_normalize_tagfix_state.json"


def _read_tracknum(local: Path) -> int:
    """Current track-number tag, or -1."""
    try:
        from mutagen import File as MF
        a = MF(local)
        if not a or not a.tags:
            return -1
        for k in ("TRCK", "tracknumber", "trkn", "\xa9trk"):
            v = a.tags.get(k)
            if v:
                s = str(v[0] if isinstance(v, list) else v)
                s = s.split("/")[0].strip().strip("()[]' ")
                if s.isdigit():
                    return int(s)
    except Exception:
        pass
    return -1


def _file_num(filename: str) -> str:
    """The 'NN' currently in 'Artist - Album - NN Title.ext', or ''."""
    stem = os.path.splitext(filename)[0]
    bits = [b.strip() for b in stem.split(" - ")]
    if len(bits) < 3:
        return ""
    m = dm._NUM.match(" - ".join(bits[2:]).strip())
    return m.group(0).strip().rstrip(".-").strip() if m else ""


def _best_canon(ftitle: str, fnum: str, canon: list):
    """canon = [(track_number:int, title:str, fnorm:str)]. Return the best
    (track_number, title) match or (None, None). File's own number breaks ties."""
    a = _fz(ftitle)
    if not a or len(a) < 2:
        return None, None
    try:
        fnum_i = int(fnum)
    except (TypeError, ValueError):
        fnum_i = -1
    best = (0.0, False, None)          # (score, num_matches_file, entry)
    for tnum, title, fnorm in canon:
        s = 1.0 if a == fnorm else difflib.SequenceMatcher(None, a, fnorm).ratio()
        key = (s, int(tnum) == fnum_i)
        if key > (best[0], best[1]):
            best = (s, key[1], (tnum, title))
    if best[0] >= _MATCH_MIN:
        return best[2]
    return None, None


def _norm_artist_album(parsed):
    artist = collections.Counter(p[1] for p in parsed).most_common(1)[0][0]
    album = collections.Counter(p[2] for p in parsed).most_common(1)[0][0]
    return artist, album


def _write_tracknum(local: Path, tnum: int, is_mp3: bool) -> bool:
    """Set the track-number tag (the Sony player orders by this, not filename)."""
    try:
        if is_mp3:
            from mutagen.id3 import ID3, TRCK
            from mutagen.mp3 import MP3
            from id3_helpers import save_v23_id3
            try:
                id3 = ID3(local)
            except Exception:
                MP3(local).add_tags(); id3 = ID3(local)
            id3.delall("TRCK")
            id3.add(TRCK(encoding=3, text=[str(tnum)]))
            save_v23_id3(id3)
        else:
            from mutagen.flac import FLAC
            a = FLAC(local)
            a["tracknumber"] = str(tnum)
            a.save()
        return True
    except Exception as e:
        print(f"   ! tag write failed ({local.name}): {e}")
        return False


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--artist", default="")
    ap.add_argument("--fix-tags", action="store_true",
                    help="also rewrite the track-number TAG on renumbered files "
                         "(pull/modify/push — slow, but this is what actually "
                         "reorders the album in the Sony player)")
    ap.add_argument("--exhaustive", action="store_true",
                    help="don't trust filenames: check EVERY album folder against "
                         "its canonical tracklist, not just ones with a local dup "
                         "signal. Catches scrambled track-number TAGs on folders "
                         "whose filenames look clean (e.g. Tyler IGOR). Implies "
                         "--fix-tags. Slow (header-pull per file, hours) but "
                         "resumable + probe-gated on clean folders.")
    args = ap.parse_args()
    if args.exhaustive:
        args.fix_tags = True

    try:
        protected = wd._load_favplaylist_protected_paths()
    except Exception:
        protected = set()

    files, _ = wd._bulk_device_scan(wd._default_storages())
    print(f"scanned {len(files)} file(s), {len(protected)} protected path(s)")

    folder_files: dict = collections.defaultdict(list)
    for f in files:
        folder_files[(f["storage"], tuple(f["parts"]))].append(f)

    n_del = n_ren = n_pin_block = n_folders = n_notl = n_unmatched = n_tag = 0
    tl_cache: dict = {}

    tagfix_done: set = set()
    if args.fix_tags and TAGFIX_STATE.exists():
        try:
            tagfix_done = set(json.loads(TAGFIX_STATE.read_text(encoding="utf-8")))
        except Exception:
            pass

    def _save_tagfix():
        try:
            TAGFIX_STATE.write_text(json.dumps(sorted(tagfix_done)), encoding="utf-8")
        except Exception:
            pass

    for (storage, parts), gfiles in sorted(folder_files.items()):
        if not parts or parts[0].lower() != MUSIC_ROOT.lower() or len(parts) < 2:
            continue
        if TRASH in parts:
            continue

        parsed = []
        for f in gfiles:
            a, al, title = dm._split_name(f["filename"])
            if a and al and title:
                parsed.append((f, a, al, title))
        if len(parsed) < 2 or len(parsed) != len(gfiles):
            continue   # unparseable names — leave for reorganize

        artist, album = _norm_artist_album(parsed)
        if args.artist and wd._norm(artist) != wd._norm(args.artist):
            continue

        # cheap local signal: 2+ files with the same fuzzy title, or a repeated
        # raw track number. Clean folders normally never hit Deezer — but in
        # --exhaustive mode we check them anyway (scrambled TRCK tags on a
        # folder whose filenames are a clean 1..N sequence are otherwise
        # invisible here — the Tyler IGOR case).
        fuzz_groups = collections.Counter(_fz(t) for _f, _a, _al, t in parsed)
        raw_nums = collections.Counter(_file_num(f["filename"]) for f, *_ in parsed)
        raw_nums.pop("", None)
        has_local_signal = (any(c > 1 for c in fuzz_groups.values())
                            or any(c > 1 for c in raw_nums.values()))
        if not has_local_signal and not args.exhaustive:
            continue

        rel = "/".join(parts)
        base = dm._base_album(album)
        sroot = adb._get_storage_path(storage)

        # canonical tracklist
        ck = (wd._norm(artist), wd._norm(base))
        if ck not in tl_cache:
            tl = []
            try:
                albums = ac.fetch_artist_albums(artist, include_types=("album", "ep"))
                capd = [x for x in albums
                        if wd._norm(dm._base_album(x["name"])) == wd._norm(base)]
                capd.sort(key=lambda x: -(x.get("total_tracks") or 0))
                if capd:
                    tl = ac.fetch_album_tracklist(capd[0]["id"])
            except Exception as e:
                print(f"   ! [{artist} - {base}] tracklist fetch failed: {e}")
            tl_cache[ck] = [(t["track_number"], t["title"], _fz(t["title"])) for t in tl]
        canon = tl_cache[ck]

        if not canon:
            if has_local_signal:
                n_folders += 1
                print(f"\n== {storage}/{rel}   ({artist} — {album})")
                n_notl += 1
                print("   ! no canonical tracklist — skipped (no safe way to dedup)")
            continue

        def _prot(f):
            hp = f"{storage}/" + "/".join(list(parts) + [f["filename"]])
            return hp.replace("\\", "/").strip() in protected

        # --exhaustive PROBE: a clean-looking folder (no dup signal) only earns a
        # full pass if a cheap 2-file tag check shows the TRCK tags are actually
        # wrong. Skips the header-pull-everything cost on the ~90% of folders
        # that are already fine.
        if args.exhaustive and not has_local_signal:
            import tempfile as _tf, shutil as _sh2
            _bad = False
            _by_num = {_file_num(f["filename"]): (f, t) for f, _a, _al, t in parsed}
            for _n in sorted(k for k in _by_num if str(k).isdigit())[:2]:
                pf, pt = _by_num[_n]
                _ck2 = f"{storage}/{rel}/{pf['filename']}"
                if _ck2 in tagfix_done:
                    continue
                _tnum, _ct = _best_canon(pt, _n, canon)
                if _tnum is None:
                    continue
                _tmp = Path(_tf.mkdtemp()); _lp = _tmp / pf["filename"]
                try:
                    _ok = adb.read_file_header_from_device(
                        src_parts=list(parts), filename=pf["filename"], dest_local=_lp,
                        device_name=config.DEVICE_NAME, storage_name=storage, max_bytes=300_000)
                    if _ok and _lp.exists():
                        _cur = _read_tracknum(_lp)
                        if _cur != -1 and _cur != _tnum:
                            _bad = True
                        elif _cur == _tnum:
                            tagfix_done.add(_ck2)
                finally:
                    _sh2.rmtree(_tmp, ignore_errors=True)
            if not _bad:
                continue   # probe clean — leave this folder alone

        n_folders += 1
        print(f"\n== {storage}/{rel}   ({artist} — {album})   [exhaustive]"
              if args.exhaustive and not has_local_signal
              else f"\n== {storage}/{rel}   ({artist} — {album})")
        print(f"   canonical tracklist: {len(canon)} tracks (Deezer)")

        def _rank(item):
            f = item[0]
            ext = os.path.splitext(f["filename"])[1].lower()
            return (_prot(f), dm._QUAL.get(ext, 0), f.get("size") or 0)

        # match every file to a canonical track
        by_canon: dict = collections.defaultdict(list)   # tnum -> [(f, title, ctitle)]
        unmatched: list = []
        for f, _a, _al, title in parsed:
            tnum, ctitle = _best_canon(title, _file_num(f["filename"]), canon)
            if tnum is None:
                unmatched.append((f, title))
                continue
            by_canon[tnum].append((f, title, ctitle))

        # unmatched files (skits, interludes, bonus tracks not on Deezer's
        # edition): can't renumber them, but a mp3+flac pair of the SAME one is
        # still a duplicate — dedup by fuzzy title within the folder, keep best.
        u_groups: dict = collections.defaultdict(list)
        for f, t in unmatched:
            u_groups[_fz(t)].append((f, t))
        for uk, ug in u_groups.items():
            if len(ug) < 2:
                n_unmatched += 1
                print(f"   ??  no canonical match, left alone: {ug[0][0]['filename']}")
                continue
            ug.sort(key=lambda it: _rank((it[0],)), reverse=True)
            print(f"   ??  keep best of {len(ug)} unmatched '{ug[0][1]}': {ug[0][0]['filename']}")
            for f, t in ug[1:]:
                if _prot(f):
                    print(f"   PIN  keep unmatched dup (protected): {f['filename']}")
                    continue
                print(f"   DEL  {f['filename']}   (unmatched dup of '{ug[0][1]}')")
                if args.execute:
                    src = f"{sroot}/{rel}/{f['filename']}"
                    adb._rm_f(src)
                    if not adb._exists(src):
                        n_del += 1

        keepers: dict = {}   # tnum -> (f, ctitle)
        for tnum, group in by_canon.items():
            group.sort(key=_rank, reverse=True)
            keep_f, _kt, keep_ct = group[0]
            keepers[tnum] = (keep_f, keep_ct)
            for f, t, _ct in group[1:]:
                if _prot(f):
                    print(f"   PIN  keep dup (protected): {f['filename']}")
                    continue
                print(f"   DEL  {f['filename']}   (dup of canon #{tnum:02d} '{_ct}')")
                if args.execute:
                    src = f"{sroot}/{rel}/{f['filename']}"
                    adb._rm_f(src)
                    if not adb._exists(src):
                        n_del += 1

        # renumber survivors whose track number is actually WRONG. A file
        # that's already at its canonical number is left as-is even if its
        # title still carries a "(Album Version (Explicit))" suffix — the
        # player shows the TAG title, not the filename, so a cosmetic-only
        # rename isn't worth an adb mv per file over a flaky link (protected
        # files included — a rename keeps the content-matched favorite and
        # favsync rebuilds the M3U8s, but only do it when it fixes ordering).
        def _numi(fn):
            v = _file_num(fn)
            return int(v) if str(v).isdigit() else -1

        # --fix-tags: pull each keeper, and if its track-number TAG (what the
        # Sony player orders by) disagrees with canonical, rewrite the tag +
        # rename the file. Independent of the filename so it still works after
        # a prior Option-A rename. Resumable via TAGFIX_STATE.
        if args.fix_tags and args.execute:
            import tempfile, shutil
            for tnum, (f, ctitle) in sorted(keepers.items()):
                fn = f["filename"]
                skey = f"{storage}/{rel}/{fn}"
                if skey in tagfix_done:
                    continue
                ext = os.path.splitext(fn)[1].lower()
                tmp = Path(tempfile.mkdtemp()); lp = tmp / fn
                try:
                    ok = adb.read_file_from_device(
                        src_parts=list(parts), filename=fn, dest_local=lp,
                        device_name=config.DEVICE_NAME, storage_name=storage)
                    if not (ok and lp.exists()):
                        continue
                    cur_tag = _read_tracknum(lp)
                    if cur_tag == tnum:
                        tagfix_done.add(skey); _save_tagfix()
                        continue
                    if _write_tracknum(lp, tnum, ext == ".mp3"):
                        adb.copy_file_to_device(
                            src=lp, dest_parts=list(parts),
                            device_name=config.DEVICE_NAME, storage_name=storage,
                            overwrite=True)
                        n_tag += 1
                        tagfix_done.add(skey)
                        if n_tag % 20 == 0:
                            _save_tagfix()
                        print(f"   TAG  {fn}  TRCK {cur_tag} -> {tnum}")
                except Exception as e:
                    print(f"   ! tag fix {fn}: {e}")
                finally:
                    shutil.rmtree(tmp, ignore_errors=True)
            _save_tagfix()

        # rename the FILE to the canonical number when its filename number is
        # wrong (cheap `mv`; the tag fix above is the part that reorders the
        # player, this just keeps the two consistent).
        planned = []
        taken = {_numi(f["filename"]) for tnum, (f, _c) in keepers.items()
                 if _numi(f["filename"]) == tnum}
        for tnum, (f, ctitle) in sorted(keepers.items()):
            if _numi(f["filename"]) == tnum:
                continue
            ext = os.path.splitext(f["filename"])[1].lower()
            final_fn = f"{dm._sanitize(artist)} - {dm._sanitize(base)} - {int(tnum):02d} {dm._sanitize(ctitle)}{ext}"
            if final_fn == f["filename"]:
                taken.add(tnum)
                continue
            if tnum in taken:
                print(f"   ! slot {int(tnum):02d} already assigned — skip renumber of {f['filename']}")
                n_pin_block += 1
                continue
            taken.add(tnum)
            planned.append((f["filename"], final_fn, tnum))
            tag = " [fav/pl]" if _prot(f) else ""
            print(f"   REN  {f['filename']}  ->  {final_fn}{tag}")

        if args.execute and planned:
            for src_fn, _f, _n in planned:
                adb._mv(f"{sroot}/{rel}/{src_fn}", f"{sroot}/{rel}/{src_fn}{_TMP}")
            for src_fn, final_fn, _n in planned:
                if adb._mv(f"{sroot}/{rel}/{src_fn}{_TMP}", f"{sroot}/{rel}/{final_fn}"):
                    n_ren += 1

    verb = "done" if args.execute else "DRY-RUN"
    print(f"\n{verb}: folders_touched={n_folders} hard_deleted_dupes={n_del} "
          f"tag_fixed={n_tag} renumbered={n_ren} slot_blocked={n_pin_block} "
          f"no_tracklist={n_notl} unmatched_left_alone={n_unmatched}")
    if not args.execute:
        print("pass --execute to apply (deletes are HARD `rm -f`)")
    if args.fix_tags:
        _save_tagfix()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
